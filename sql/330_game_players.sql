-- Game module, part 4: players, inventory, join/leave, who-can-see-whom.
-- mc.player is tuned for in-place (HOT) updates: fillfactor 60 and NO index on any column that changes every tick
-- (position, rotation, chunk, sent_*).  The only indexes are on uuid, entity_id and conn_id, which change at join/leave only.

create table if not exists mc.game_state (            -- one row: clock, weather, spawn.  (World storage is another module's.)
    id int primary key default 1 check (id = 1),
    game_time bigint not null default 0,
    day_time  bigint not null default 0,
    raining boolean not null default false, thundering boolean not null default false,
    spawn_x float8 not null default 0.5, spawn_y float8 not null default 64, spawn_z float8 not null default 0.5, spawn_yaw real not null default 0
);
insert into mc.game_state default values on conflict do nothing;

create sequence if not exists mc.entity_id_seq;       -- entity ids are per run in vanilla too (the capture shows 1, 2, 3 ...)

create table if not exists mc.player (
    uuid uuid primary key,
    name text not null,
    -- persistent
    gamemode smallint not null default 0,              -- 0 survival, 1 creative, 2 adventure, 3 spectator
    health real not null default 20, food int not null default 20, saturation real not null default 5, xp_level int not null default 0,
    held_slot smallint not null default 0,
    first_seen timestamptz not null default now(), last_seen timestamptz,
    -- session
    conn_id int,                                       -- null = offline
    entity_id int,
    x float8 not null default 0, y float8 not null default 0, z float8 not null default 0,
    yaw real not null default 0, pitch real not null default 0, on_ground boolean not null default true,
    chunk_x int not null default 0, chunk_z int not null default 0,
    -- what other players were last told (so every viewer's deltas share one base, like vanilla's tracker)
    sent_qx bigint not null default 0, sent_qy bigint not null default 0, sent_qz bigint not null default 0,
    sent_yaw real not null default 0, sent_pitch real not null default 0, last_sent_tick bigint not null default 0,
    vis_dirty boolean not null default false,          -- changed chunk since the last visibility refresh
    teleport_id int not null default 0, awaiting_teleport int,
    keepalive_id bigint, keepalive_sent_tick bigint, latency_ms int not null default 0,
    chat_sent int not null default 0,                  -- messages this player has sent (the per-sender `index` of player_chat)
    chat_recv int not null default 0,                  -- player_chat packets this player has been sent (the per-recipient `globalIndex`)
    inv_state int not null default 1                   -- container state id: 1 after the join's container_set_content, +1 per server-sent slot update (as observed)
) with (fillfactor = 60);
create unique index if not exists player_entity_idx on mc.player (entity_id) where entity_id is not null;
create index if not exists player_conn_idx on mc.player (conn_id) where conn_id is not null;
create index if not exists player_name_idx on mc.player (lower(name));

-- Inventory slots use the player-inventory container numbering of vanilla's menu: 0 crafting result, 1-4 crafting grid, 5-8 armor,
-- 9-35 main inventory, 36-44 hotbar, 45 off hand.  Only non-empty slots have rows.
create table if not exists mc.inventory_slot (
    player uuid not null references mc.player(uuid) on delete cascade,
    slot smallint not null check (slot between 0 and 45),
    item text not null,                                -- minecraft:stone (must exist in ref.item)
    count smallint not null check (count between 1 and 99),
    components jsonb,                                  -- data components other than the default; null = none
    primary key (player, slot)
);

-- Queues between this module and the connection layer (the gateway side moves rows between these and net.inbox/net.outbox).
create unlogged table if not exists mc.play_in  (seq bigint generated always as identity, conn_id int not null, packet_id int not null, body bytea not null);
-- The tick CLAIMS the rows of play_in it will process (delete ... returning into play_in_work) so a packet the gateway inserts while the tick runs stays queued
-- for the next tick instead of being deleted unprocessed; the handlers read and delete play_in_work only.
create unlogged table if not exists mc.play_in_work (seq bigint generated by default as identity, conn_id int not null, packet_id int not null, body bytea not null);
create unlogged table if not exists mc.play_out (seq bigint generated always as identity, conn_id int not null, data bytea not null);
create unlogged table if not exists mc.kick     (conn_id int primary key, reason_nbt bytea not null);  -- close these connections after flushing play_out
create unlogged table if not exists mc.visible  (        -- viewer can see target (both are entity ids; viewer_conn cached for fan-out)
    viewer_eid int not null, target_eid int not null, viewer_conn int not null, primary key (viewer_eid, target_eid));
create index if not exists visible_target_idx on mc.visible (target_eid);

create or replace function mc.item_id(item_name text) returns int language sql stable parallel safe as $$
  select protocol_id from ref.registry where registry = 'minecraft:item' and name = item_name $$;

create or replace function mc.set_slot(p_uuid uuid, p_slot int, p_item text, p_count int, p_components jsonb default null) returns void language plpgsql as $$
begin
  if p_count is null or p_count <= 0 or p_item is null then delete from mc.inventory_slot where player = p_uuid and slot = p_slot; return; end if;
  if mc.item_id(p_item) is null then raise exception 'unknown item %', p_item using errcode = '22023'; end if;
  insert into mc.inventory_slot values (p_uuid, p_slot, p_item, p_count, p_components)
  on conflict (player, slot) do update set item = excluded.item, count = excluded.count, components = excluded.components;
end $$;

------------------------------------------------------------------------------------------------ kick
-- Disconnect packet (play phase: network NBT component) and mark the connection for closing.
create or replace function mc.pkt_disconnect(component_nbt bytea) returns bytea language sql stable parallel safe as $$ select mc.cb('disconnect', component_nbt) $$;
create or replace function mc.kick(p_conn int, reason_key text, reason_args text[] default null) returns void language plpgsql as $$
declare nbt bytea := proto.nbt_root(mc.disconnect_nbt(reason_key, reason_args));
begin
  insert into mc.play_out (conn_id, data) values (p_conn, mc.pkt_disconnect(nbt));
  insert into mc.kick values (p_conn, nbt) on conflict do nothing;
end $$;

create or replace function mc.pkt_teleport_entity(entity_id int, x float8, y float8, z float8, dx float8, dy float8, dz float8, yaw real, pitch real, on_ground boolean)
returns bytea language sql stable parallel safe as $$      -- layout from the bytecode (id, position, delta, yaw, pitch, relative flags, on ground); NOT byte-verified
  select mc.cb('teleport_entity', proto.varint(entity_id) || proto.f64(x) || proto.f64(y) || proto.f64(z) || proto.f64(dx) || proto.f64(dy) || proto.f64(dz)
       || proto.f32(yaw) || proto.f32(pitch) || proto.i32(0) || proto.bool(on_ground)) $$;

------------------------------------------------------------------------------------------------ join / leave
-- Called when a connection finishes login and configuration.  Creates or loads the player, gives it an entity id, and queues what others and the
-- joiner must be told (join message, tab list).  Entities become visible in refresh_visibility().  Returns the player row.
create or replace function mc.on_join(p_conn int, p_uuid uuid, p_name text) returns mc.player language plpgsql as $$
declare p mc.player; gs mc.game_state; old_conn int;
begin
  select * into gs from mc.game_state;
  select conn_id into old_conn from mc.player where uuid = p_uuid;
  if old_conn is not null then perform mc.on_leave(old_conn, 'multiplayer.disconnect.duplicate_login'); end if;   -- vanilla kicks the older session
  insert into mc.player (uuid, name, gamemode, x, y, z, yaw, chunk_x, chunk_z)
  values (p_uuid, p_name, case mc.prop('gamemode') when 'creative' then 1 when 'adventure' then 2 when 'spectator' then 3 else 0 end,
          gs.spawn_x, gs.spawn_y, gs.spawn_z, gs.spawn_yaw, floor(gs.spawn_x / 16)::int, floor(gs.spawn_z / 16)::int)
  on conflict (uuid) do update set name = excluded.name
  returning * into p;
  update mc.player set conn_id = p_conn, entity_id = nextval('mc.entity_id_seq'), vis_dirty = true,
         chunk_x = floor(x / 16)::int, chunk_z = floor(z / 16)::int,
         sent_qx = mc.quant(x), sent_qy = mc.quant(y), sent_qz = mc.quant(z), sent_yaw = yaw, sent_pitch = pitch,
         awaiting_teleport = null, keepalive_id = null, keepalive_sent_tick = null, inv_state = 1, chat_recv = 0
   where uuid = p_uuid returning * into p;
  -- 1. everyone (including the joiner) gets the join message, then the joiner's tab list entry (vanilla's order)
  insert into mc.play_out (conn_id, data)
    select o.conn_id, mc.pkt_system_chat(proto.nbt_root(mc.tc_translate('multiplayer.player.joined', array[mc.tc_player(p.uuid, p.name)], 'yellow')))
      from mc.player o where o.conn_id is not null order by o.entity_id;
  insert into mc.play_out (conn_id, data)
    select o.conn_id, mc.pkt_player_info_add(array[mc.pie_add(p.uuid, p.name, p.gamemode)]) from mc.player o where o.conn_id is not null order by o.entity_id;
  -- 2. the joiner learns the players that are already online
  insert into mc.play_out (conn_id, data)
    select p_conn, mc.pkt_player_info_add(array_agg(mc.pie_add(o.uuid, o.name, o.gamemode) order by o.entity_id))
      from mc.player o where o.conn_id is not null and o.uuid <> p.uuid having count(*) > 0;
  return p;
end $$;

-- Called when a connection closes (or is replaced).  Tells viewers to drop the entity and everyone to drop the tab entry.
create or replace function mc.on_leave(p_conn int, kick_key text default null) returns void language plpgsql as $$
declare p mc.player;
begin
  select * into p from mc.player where conn_id = p_conn;
  if not found then return; end if;
  if kick_key is not null then perform mc.kick(p_conn, kick_key); end if;
  insert into mc.play_out (conn_id, data)
    select v.viewer_conn, mc.pkt_remove_entities(array[p.entity_id]) from mc.visible v where v.target_eid = p.entity_id and v.viewer_conn <> p_conn;
  insert into mc.play_out (conn_id, data)
    select o.conn_id, mc.pkt_system_chat(proto.nbt_root(mc.tc_translate('multiplayer.player.left', array[mc.tc_player(p.uuid, p.name)], 'yellow')))
      from mc.player o where o.conn_id is not null and o.uuid <> p.uuid order by o.entity_id;
  insert into mc.play_out (conn_id, data)
    select o.conn_id, mc.pkt_player_info_remove(array[p.uuid]) from mc.player o where o.conn_id is not null and o.uuid <> p.uuid order by o.entity_id;
  delete from mc.visible where viewer_eid = p.entity_id or target_eid = p.entity_id;
  update mc.player set conn_id = null, entity_id = null, last_seen = now(), vis_dirty = false where uuid = p.uuid;
end $$;

------------------------------------------------------------------------------------------------ who sees whom
-- Visibility rule (simplification, documented): two players see each other when their chunk coordinates differ by at most min(view-distance, 32)
-- in both axes.  Maintained incrementally: only players that changed chunk (vis_dirty) are compared against everyone, so the work is
-- (number of dirty players) x (online players) instead of online^2.  Emits add_entity / remove_entities to the affected viewers.
create or replace function mc.refresh_visibility() returns table(added int, removed int) language plpgsql as $$
declare r int := least(mc.prop_int('view-distance'), 32);
begin
  create temp table if not exists _vis_want (viewer_eid int, target_eid int, viewer_conn int, primary key (viewer_eid, target_eid)) on commit delete rows;
  delete from _vis_want;
  perform mc.prof('vis start');
  -- A slim, freshly analysed copy of the online players: the planner then knows how few are dirty (measured: comparing against the wide, never-analysed
  -- mc.player made it compare every pair, 90 ms for 20 dirty players among 500).
  create temp table if not exists _vis_on (eid int primary key, conn int, cx int, cz int, dirty boolean) on commit delete rows;
  delete from _vis_on;
  insert into _vis_on select entity_id, conn_id, chunk_x, chunk_z, vis_dirty from mc.player where conn_id is not null;
  analyze _vis_on;
  insert into _vis_want
  select a.eid, b.eid, a.conn from _vis_on a join _vis_on b on b.eid <> a.eid and abs(a.cx - b.cx) <= r and abs(a.cz - b.cz) <= r where a.dirty
  union
  select a.eid, b.eid, a.conn from _vis_on b join _vis_on a on a.eid <> b.eid and abs(a.cx - b.cx) <= r and abs(a.cz - b.cz) <= r where b.dirty;

  perform mc.prof('vis A compute wanted pairs');
  -- newly visible: add_entity at the position the other viewers were last told (shared delta base)
  with ins as (
    insert into mc.visible (viewer_eid, target_eid, viewer_conn)
    select w.viewer_eid, w.target_eid, w.viewer_conn from _vis_want w
     where not exists (select 1 from mc.visible v where v.viewer_eid = w.viewer_eid and v.target_eid = w.target_eid)
    returning viewer_eid, target_eid, viewer_conn),
  q as (
    insert into mc.play_out (conn_id, data)
    select i.viewer_conn, string_agg(mc.pkt_add_player_entity(t.entity_id, t.uuid, t.sent_qx / 4096.0, t.sent_qy / 4096.0, t.sent_qz / 4096.0, t.sent_yaw, t.sent_pitch, t.sent_yaw), '\x'::bytea order by t.entity_id)
      from ins i join mc.player t on t.entity_id = i.target_eid group by i.viewer_conn
    returning 1)
  select (select count(*) from ins) into added;

  perform mc.prof('vis B insert new pairs + add_entity packets');
  -- no longer visible (only pairs involving a dirty player can have changed)
  with del as (
    delete from mc.visible v
     where (v.viewer_eid in (select eid from _vis_on where dirty) or v.target_eid in (select eid from _vis_on where dirty))
       and not exists (select 1 from _vis_want w where w.viewer_eid = v.viewer_eid and w.target_eid = v.target_eid)
    returning v.viewer_conn, v.target_eid),
  q as (
    insert into mc.play_out (conn_id, data)
    select viewer_conn, mc.pkt_remove_entities(array_agg(target_eid)) from del group by viewer_conn
    returning 1)
  select (select count(*) from del) into removed;

  perform mc.prof('vis C delete old pairs + remove packets');
  update mc.player set vis_dirty = false where vis_dirty;
  perform mc.prof('vis D clear dirty flags');
  return next;
end $$;
