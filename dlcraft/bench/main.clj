(ns main
  "Benchmark driver:  tools/clj.sh -M -m main run [facet ...]   |   report
     facets: gen chunk point fill analytics bulk storage tick hot reader chat inv dyn commit writers crash readers mem"
  (:require [clojure.string :as str]
            [datalevin.core :as d]
            [dlcraft.store :as st]
            [pgx] [util :as u] [rec]
            [facets1 :as f1] [facets2 :as f2] [facets3 :as f3]
            [cheshire.core :as json]))

(def dl-dir "/srv/dlcraft/dl/bench")

(defn render-md [results]
  (let [by-facet (group-by :facet results)
        facet-order (distinct (map :facet results))]
    (with-out-str
      (doseq [f facet-order]
        (println (str "\n### " f "\n"))
        (println "| metric | engine | value | unit | note |")
        (println "|---|---|--:|---|---|")
        (let [by-metric (group-by :metric (get by-facet f))]
          (doseq [m (distinct (map :metric (get by-facet f)))]
            (let [rows (get by-metric m)]
              (doseq [r rows]
                (println (format "| %s | %s | %s | %s | %s |" (:metric r) (:engine r) (u/fmt (:value r)) (:unit r) (or (:note r) "")))))))))))

(defn write-results! []
  (let [prev (try (json/parse-string (slurp "results/results.json") true) (catch Throwable _ []))
        mine @rec/R
        mine-facets (set (map :facet mine))
        ;; keep earlier rows of facets that were not re-run (keywords come back as strings: normalise)
        keep (for [r prev :when (not (mine-facets (:facet r)))] (-> r (update :better keyword)))
        rs (vec (concat keep mine))]
    (.mkdirs (java.io.File. "results"))
    (u/write-json! "results/results.json" rs)
    (spit "results/RESULTS.md" (str "# dlcraft raw results\n\nGenerated by `tools/clj.sh -M -m main run`.  See README.md for the reading of these numbers.\n" (render-md rs)))
    (println "\nwrote results/results.json and results/RESULTS.md (" (count rs) "rows)")))

(def all-facets ["gen" "chunk" "point" "fill" "analytics" "tick" "hot" "reader" "chat" "inv" "dyn" "bulk" "storage" "commit" "writers" "readers" "crash" "mem"])

(defn -main [cmd & args]
  (case cmd
    "run"
    (let [wanted (if (seq args) (set args) (set all-facets))
          env (st/open dl-dir {:fresh? (contains? wanted "gen") :profile :nometasync})
          pg (pgx/connect true)
          ctx {:env env :pg pg}]
      (pgx/exec! pg "set synchronous_commit = off")
      (when (contains? wanted "gen") (doseq [f ["mc.reset_world()" "mc.reset_players()" "mc.reset_sched()"]] (pgx/query pg (str "select " f))))
      (println "datalevin profile" (:profile env) "| postgres" (pgx/query1 pg "show synchronous_commit") "world: " (pgx/query1 pg "select count(*) from mc.chunk") "chunks")
      (when (wanted "gen") (f1/f-gen ctx) (f3/snapshot-rss! "after generating 640 chunks"))
      (when (wanted "chunk") (f1/f-chunk-read ctx))
      (when (wanted "point") (f1/f-point ctx))
      (when (wanted "fill") (f1/f-fill ctx))
      (when (wanted "analytics") (f1/f-analytics ctx))
      (when (wanted "tick") (f2/f-tick ctx) (f3/snapshot-rss! "after the tick scenarios (up to 2000 players)"))
      (when (wanted "hot") (f2/f-hot ctx))
      (when (wanted "reader") (f2/f-reader ctx))
      (when (wanted "chat") (f2/f-chat ctx))
      (when (wanted "inv") (f2/f-inv ctx))
      (when (wanted "dyn") (f2/f-dyn ctx))
      (when (wanted "bulk") (f1/f-bulk ctx))
      (when (wanted "storage") (f1/f-storage ctx))
      (when (wanted "commit") (f3/f-commit ctx))
      (when (wanted "writers") (f3/f-writers ctx))
      (when (wanted "readers") (f3/f-readers ctx))
      (when (wanted "crash") (st/close env) (.close pg) (f3/f-crash ctx))
      (when (wanted "mem") (f3/snapshot-rss! "end of run"))
      (write-results!)
      (shutdown-agents) (System/exit 0))
    "report" (do (reset! rec/R (json/parse-string (slurp "results/results.json") true)) (write-results!))))
