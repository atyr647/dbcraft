-- nobody changed chunk: nothing is sent and nothing changes
create or replace function t.st_noop() returns text language plpgsql as $$
declare n int;
begin
  perform t.st_build(0.5, 10, false, false);
  update net.conn c set view_cx = p.chunk_x, view_cz = p.chunk_z from mc.player p where p.conn_id = c.conn_id;
  truncate mc.play_out;
  n := net.stream_chunks();
  return n || ' players streamed, ' || (select count(*) from mc.play_out) || ' frames';
end $$;
select t.eq('streaming: nobody changed chunk is a no-op', t.st_noop(), '0 players streamed, 0 frames');
