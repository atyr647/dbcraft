create or replace function t.st_build(p_seed float8, p_n int, p_far boolean, p_edit boolean) returns void language plpgsql as $$
declare base int := case when p_far then 20 else 0 end;
begin
  perform setseed(p_seed);
  if p_far then delete from mc.chunk where cx >= 18; delete from mc.chunk_cache where cx >= 18; end if;      -- the far region starts empty in every scenario
  truncate net.conn, net.outbox, mc.play_out; delete from mc.player;
  insert into mc.player (uuid, name, conn_id, entity_id, x, y, z, chunk_x, chunk_z, vis_dirty)
  select md5(p_seed::text || i)::uuid, 's' || i, i, 500 + i, (base + cx) * 16 + 8, 64, (base + cz) * 16 + 8, base + cx, base + cz, false
    from (select i, (random() * 4)::int as cx, (random() * 4)::int as cz from generate_series(1, p_n) i) g;
  insert into net.conn (conn_id, state, compression, view_cx, view_cz)
  select conn_id, 'play', -1, chunk_x + (case when conn_id % 3 = 0 then 0 else (random() * 4 - 2)::int end), chunk_z + (case when conn_id % 5 = 0 then 0 else (random() * 4 - 2)::int end) from mc.player;
  if p_edit then update mc.chunk set dirty = true where (cx, cz) in ((1, 1), (2, 2), (3, 3), (0, 2));   -- derived data stale, cache version unchanged: the function path must recompute and clear the flag
    perform mc.set_block('minecraft:overworld', 1 * 16 + 3, -50, 2 * 16 + 5, 'minecraft:stone'); perform mc.set_block('minecraft:overworld', 3 * 16 + 1, -40, 1 * 16 + 2, 'minecraft:gold_block'); end if;
end $$;

create or replace function t.st_digest() returns jsonb language sql as $$
  select jsonb_build_object(
    'out',   (select coalesce(string_agg(conn_id || ':' || md5(d), ',' order by conn_id), '') from (select conn_id, string_agg(encode(data, 'hex'), '|' order by seq) d from mc.play_out group by conn_id) q),
    'views', (select coalesce(string_agg(conn_id || '=' || view_cx || ',' || view_cz, ';' order by conn_id), '') from net.conn),
    'frames', (select count(*) from mc.play_out),
    'stale_chunks', (select count(*) from mc.chunk where dirty or hm_dirty)) $$;

create or replace function t.st_compare(p_seed float8, p_n int, p_far boolean, p_edit boolean) returns text language plpgsql as $$
declare na int; nb int; da jsonb; db jsonb; diff text; gen_far int;
begin
  perform t.st_build(p_seed, p_n, p_far, p_edit);
  drop table if exists t_s_player, t_s_conn; create table t_s_player as select * from mc.player; create table t_s_conn as select * from net.conn;
  drop table if exists t_s_dirty; create table t_s_dirty as select dimension, cx, cz, dirty, hm_dirty from mc.chunk where dirty or hm_dirty;      -- the chunk state the original is about to clean
  na := net.stream_chunks_general(); da := t.st_digest();
  update mc.chunk c set dirty = d.dirty, hm_dirty = d.hm_dirty from t_s_dirty d where c.dimension = d.dimension and c.cx = d.cx and c.cz = d.cz;      -- the rewrite starts from the same state
  select count(*) into gen_far from mc.chunk where cx >= 18;
  if p_far then delete from mc.chunk where cx >= 18; delete from mc.chunk_cache where cx >= 18; end if;           -- the chunks the original generated must be generated again
  truncate mc.play_out; delete from net.conn; insert into net.conn select * from t_s_conn;
  nb := net.stream_chunks(); db := t.st_digest();
  if na is distinct from nb then return format('return values differ: original %s rewrite %s', na, nb); end if;
  select string_agg(a.key, ',') into diff from jsonb_each_text(da) a join jsonb_each_text(db) b using (key) where a.value is distinct from b.value;
  if p_far and (select count(*) from mc.chunk where cx >= 18) is distinct from gen_far then return 'the rewrite did not regenerate the same missing chunks'; end if;
  return coalesce('differs in: ' || diff, 'same');
end $$;

