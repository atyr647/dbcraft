------------------------------------------------------------------------------------------------ visibility
create or replace function t.vis_build(p_seed float8, p_n int, p_move float8) returns void language plpgsql as $$
begin
  perform setseed(p_seed);
  truncate mc.play_out, mc.visible, mc.kick; delete from mc.player;
  insert into mc.player (uuid, name, conn_id, entity_id, x, y, z, yaw, pitch, chunk_x, chunk_z, sent_qx, sent_qy, sent_qz, sent_yaw, sent_pitch, vis_dirty, last_sent_tick)
  select md5(p_seed::text || i)::uuid, 'v' || i, case when i % 9 = 0 then null else i end, case when i % 9 = 0 then null else 200 + i end,
         cx * 16 + 8, 64, cz * 16 + 8, (i % 360)::real, 0, cx, cz, mc.quant(cx * 16 + 8), mc.quant(64), mc.quant(cz * 16 + 8), (i % 360)::real, 0, true, 0
    from (select i, (random() * 6)::int as cx, (random() * 6)::int as cz from generate_series(1, p_n) i) g;
  perform * from mc.refresh_visibility_general();            -- everybody dirty: the initial visible set
  truncate mc.play_out;
  -- some players cross a chunk border (and some offline players are flagged too): only those are dirty now
  update mc.player set chunk_x = (random() * 6)::int, chunk_z = (random() * 6)::int, vis_dirty = true where random() < p_move;
end $$;

create or replace function t.vis_digest() returns jsonb language sql as $$
  select jsonb_build_object(
    'visible', (select coalesce(string_agg(viewer_eid || '>' || target_eid || '@' || viewer_conn, ',' order by viewer_eid, target_eid), '') from mc.visible),
    'out',     (select coalesce(string_agg(conn_id || ':' || md5(d), ',' order by conn_id), '') from (select conn_id, string_agg(encode(data, 'hex'), '|' order by seq) d from mc.play_out group by conn_id) q),
    'dirty',   (select count(*) from mc.player where vis_dirty)) $$;

create or replace function t.vis_compare(p_seed float8, p_n int, p_move float8) returns text language plpgsql as $$
declare ra record; rb record; da jsonb; db jsonb; diff text;
begin
  perform t.vis_build(p_seed, p_n, p_move);
  drop table if exists t_v_player, t_v_vis; create table t_v_player as select * from mc.player; create table t_v_vis as select * from mc.visible;
  select * into ra from mc.refresh_visibility_general(); da := t.vis_digest();
  truncate mc.play_out, mc.visible; delete from mc.player; insert into mc.player select * from t_v_player; insert into mc.visible select * from t_v_vis;
  select * into rb from mc.refresh_visibility(); db := t.vis_digest();
  if (ra.added, ra.removed) is distinct from (rb.added, rb.removed) then return format('counters differ: original %s rewrite %s', ra, rb); end if;
  select string_agg(a.key, ',') into diff from jsonb_each_text(da) a join jsonb_each_text(db) b using (key) where a.value is distinct from b.value;
  return coalesce('differs in: ' || diff, 'same');
end $$;

