#!/usr/bin/env bash
# Regenerates tests/sql/385_*.sql and 386_*.sql: the byte-exact replay test (410) and the behaviour test (420) run through mc.server_tick_batched() instead of
# mc.server_tick().  Those two tests compare what the server sends with real vanilla 26.3 traffic, so passing them through the batched entry point is the proof that
# the batched pipeline sends vanilla's bytes in those scenarios.  Run this again whenever 410 or 420 change.
set -euo pipefail
cd "$(dirname "$0")/../../.."
gen() {
  { echo "-- GENERATED by tests/bench/batch/gen_tests.sh from tests/sql/$2: the same scenarios and checks, with mc.server_tick() replaced by mc.server_tick_batched().  Do not edit."
    sed 's/mc\.server_tick()/mc.server_tick_batched()/g' "tests/sql/$2"; } > "tests/sql/$1"
}
gen 385_batch_replay.sql 410_integration_replay.sql
gen 386_batch_behaviour.sql 420_integration_behaviour.sql
echo "generated tests/sql/385_batch_replay.sql tests/sql/386_batch_behaviour.sql"
