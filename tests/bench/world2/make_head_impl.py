#!/usr/bin/env python3
"""Writes tests/bench/world2/head_impl.sql: the fill and broadcast functions of the commit this work started from (046d1e2), copied into the schema bench_head, so the
new implementations can be timed against them in one session (A/B, interleaved).   usage: tests/bench/world2/make_head_impl.py
The copies are frozen text from git history; nothing in sql/ depends on them."""
import os, re, subprocess

BASE = "046d1e2"
SRC = {
    "sql/210_world_blocks.sql": ["fill_section", "fill"],
    "sql/432_tick_perf_world.sql": ["broadcast_block_events"],
    "sql/850_world_section_updates.sql": ["shortset_order", "cells_positions", "section_state_ids", "varint_u28", "section_update_packet"],
}
NAMES = [n for v in SRC.values() for n in v]
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
out = ["-- GENERATED by tests/bench/world2/make_head_impl.py from commit %s.  The fill and broadcast functions before the work of docs/PERF-WORLD2.md, schema bench_head." % BASE,
       "create schema if not exists bench_head;", ""]
for path, names in SRC.items():
    text = subprocess.run(["git", "show", f"{BASE}:{path}"], capture_output=True, text=True, check=True).stdout
    for n in names:
        m = re.search(r"create or replace function mc\.%s\(" % n, text)
        assert m, (path, n)
        start = m.start()
        body_open = text.index("$$", start)
        end = text.index("$$;", body_open + 2) + 3
        out.append(text[start:end]); out.append("")
sql = "\n".join(out)
for n in NAMES:
    sql = sql.replace("mc.%s(" % n, "bench_head.%s(" % n)
open("tests/bench/world2/head_impl.sql", "w").write(sql + "\n")
print("wrote tests/bench/world2/head_impl.sql with", len(NAMES), "functions")
