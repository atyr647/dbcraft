#!/usr/bin/env python3
"""Writes tests/bench/edit/old_impl.sql: the ORIGINAL (commit 971e8cb) rebuild and batch-edit functions, copied into the schema mc_old, so that the new
implementations can be timed and compared against them on the same database.   usage: tests/bench/edit/make_old_impl.py
The copies are frozen text from git history; nothing in sql/ depends on them."""
import re, subprocess

BASE = "971e8cb"
SRC = {
    "sql/210_world_blocks.sql": ["edit_section", "set_blocks"],
    "sql/220_world_compute.sql": ["sky_layer", "compute_light", "ensure_chunk_current"],
    "sql/230_world_chunk.sql": ["section_wire", "heightmaps_wire", "light_wire", "block_entities_wire", "chunk_packet_body", "chunk_packet_build", "chunk_packet"],
}
NAMES = [n for v in SRC.values() for n in v]
out = ["-- GENERATED by tests/bench/edit/make_old_impl.py from commit %s.  The original implementations, schema mc_old, for A/B timing and equivalence tests." % BASE,
       "create schema if not exists mc_old;", ""]
for path, names in SRC.items():
    text = subprocess.run(["git", "show", f"{BASE}:{path}"], capture_output=True, text=True, check=True).stdout
    for n in names:
        m = re.search(r"create or replace function mc\.%s\(" % n, text)
        assert m, (path, n)
        start = m.start()
        body_open = text.index("$$", start)                 # as $$
        end = text.index("$$;", body_open + 2) + 3
        fn = text[start:end]
        out.append(fn)
        out.append("")
sql = "\n".join(out)
for n in NAMES:
    sql = sql.replace("mc.%s(" % n, "mc_old.%s(" % n)
# the original zero-fills twice the bytes a new palette section needs (repeat('00', k) is k bytes: a long is 8, not 16); every other line is the original
bug = "decode(repeat('00', ((4096 + vpl - 1) / vpl) * 16), 'hex')"
assert bug in sql
sql = sql.replace(bug, "decode(repeat('00', ((4096 + vpl - 1) / vpl) * 8), 'hex')")       # (the original had * 16: twice the data)
open("tests/bench/edit/old_impl.sql", "w").write(sql + "\n")
print("wrote tests/bench/edit/old_impl.sql with", len(NAMES), "functions")
