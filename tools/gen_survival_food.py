#!/usr/bin/env python3
"""Generate sql/835_survival_food.sql (mc.food_item: what each edible item gives and how long eating takes) from the 26.3 classes, by READING their bytecode with javap
(the classes are never run).  The values are the arguments of the builders in net.minecraft.world.food.Foods, the Consumables constants and the item registrations of
net.minecraft.world.item.Items; nothing is guessed.

usage: tools/gen_survival_food.py [CLASSES_DIR]  > sql/835_survival_food.sql
CLASSES_DIR (default $DBCRAFT_CLASSES or /tmp/game-scratch/cls) is the extracted inner server jar, as for tools/pkt_layout.py.
Effects of food (golden apples, rotten flesh, ...) are not extracted: the table has nutrition, saturation, can-always-eat, consume time and the item left behind.
"""
import os, re, subprocess, sys

root = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("DBCRAFT_CLASSES", "/tmp/game-scratch/cls")

def javap(cls):
    env = dict(os.environ, JAVA_TOOL_OPTIONS="")
    out = subprocess.run(["javap", "-p", "-c", "-constants", "-classpath", root, cls], capture_output=True, text=True, env=env).stdout
    return [l for l in out.splitlines() if "Picked up" not in l]

def instrs(lines):
    for l in lines:
        m = re.match(r"\s+\d+: (\w+)\s*(.*)", l)
        if m: yield m.group(1), m.group(2)

def const_int(op, arg):
    if op.startswith("iconst_"): return -1 if op == "iconst_m1" else int(op[7:])
    if op in ("bipush", "sipush"): return int(arg.split()[0])
    return None

def const_float(op, arg):
    if op.startswith("fconst_"): return float(op[7:])
    m = re.search(r"float ([0-9.eE+-]+)f", arg)
    return float(m.group(1)) if op in ("ldc", "ldc_w") and m else None

# ---- Foods: FoodProperties by field name
foods, cur, args = {}, {}, []
body = javap("net.minecraft.world.food.Foods")
start = next(i for i, l in enumerate(body) if l.strip() == "static {};")
last_int = None
for op, arg in instrs(body[start:]):
    i, f = const_int(op, arg), const_float(op, arg)
    if i is not None: last_int = i
    if op == "invokestatic" and "Method stew:" in arg: cur = {"nutrition": last_int, "mod": 0.6, "always": False}
    if op == "invokevirtual" and "Builder.nutrition:" in arg: cur = {"nutrition": last_int, "mod": None, "always": False}
    if f is not None and cur and cur.get("mod") is None: last_f = f
    if op == "invokevirtual" and "Builder.saturationModifier:" in arg: cur["mod"] = last_f
    if op == "invokevirtual" and "Builder.alwaysEdible:" in arg: cur["always"] = True
    m = re.search(r"putstatic .*Field (\w+):", op + " " + arg)
    if op == "putstatic":
        foods[re.search(r"Field (\w+):", arg).group(1)] = dict(cur); cur = {}
    if f is not None: last_f = f
# the saturation: FoodConstants.saturationByModifier(nutrition, modifier) = nutrition * modifier * 2 (floats)

# ---- Consumables: consume seconds by field (defaultFood 1.6 s, defaultDrink 1.6 s, overrides before the putstatic)
cons = {}
body = javap("net.minecraft.world.item.component.Consumables")
start = next(i for i, l in enumerate(body) if l.strip() == "static {};")
secs = None
for op, arg in instrs(body[start:]):
    if op == "invokestatic" and ("defaultFood" in arg or "defaultDrink" in arg): secs = 1.6
    f = const_float(op, arg)
    if f is not None and op != "invokestatic": last = f
    if op == "invokevirtual" and "Builder.consumeSeconds:" in arg: secs = last
    if op == "putstatic": cons[re.search(r"Field (\w+):", arg).group(1)] = secs

# ---- Items: which item uses which Foods/Consumables constant, what it converts to, stack size
items = {}
body = javap("net.minecraft.world.item.Items")
start = next(i for i, l in enumerate(body) if l.strip() == "static {};")
seg = {"food": None, "cons": None, "conv": None, "stack": None}; prev_item = None; last_int = None
for op, arg in instrs(body[start:]):
    i = const_int(op, arg)
    if i is not None: last_int = i
    if op == "getstatic":
        m = re.search(r"Field net/minecraft/world/food/Foods\.(\w+):", arg)
        if m: seg["food"] = m.group(1)
        m = re.search(r"Field net/minecraft/world/item/component/Consumables\.(\w+):", arg)
        if m: seg["cons"] = m.group(1)
        m = re.search(r"Field (?:net/minecraft/world/item/Items\.)?(\w+):Lnet/minecraft/world/item/Item;", arg)
        if m: prev_item = m.group(1)
    if op == "invokevirtual" and "Item$Properties.usingConvertsTo:" in arg: seg["conv"] = prev_item
    if op == "invokevirtual" and "Item$Properties.stacksTo:" in arg: seg["stack"] = last_int
    if op == "putstatic" and re.search(r"Field (\w+):Lnet/minecraft/world/item/Item;", arg):
        name = re.search(r"Field (\w+):", arg).group(1)
        if seg["food"]: items[name] = dict(seg)
        seg = {"food": None, "cons": None, "conv": None, "stack": None}

print("-- GENERATED by tools/gen_survival_food.py from the 26.3 bytecode (Foods, Consumables, Items): do not edit by hand.")
print("-- nutrition and saturation are FoodProperties (saturation = nutrition * modifier * 2, in float); consume_ticks = (int)(consume seconds * 20);")
print("-- remainder is Item.Properties.usingConvertsTo (what is left after eating: a bowl, a bottle).  Food effects are not in the table.")
print("create table if not exists mc.food_item (item text primary key, nutrition int not null, saturation real not null, can_always_eat boolean not null, consume_ticks int not null, remainder text);")
print("delete from mc.food_item;")
print("insert into mc.food_item (item, nutrition, saturation, can_always_eat, consume_ticks, remainder) values")
rows = []
for name, it in sorted(items.items()):
    fd = foods[it["food"]]
    sat = float(__import__("struct").unpack(">f", __import__("struct").pack(">f", __import__("struct").unpack(">f", __import__("struct").pack(">f", fd["nutrition"] * fd["mod"]))[0] * 2.0))[0])
    secs = cons.get(it["cons"], 1.6) if it["cons"] else 1.6
    ticks = int(secs * 20 + 1e-6) if abs(secs * 20 - round(secs * 20)) < 1e-3 else int(secs * 20)
    rem = "'minecraft:" + it["conv"].lower() + "'" if it["conv"] else "null"
    rows.append(f"  ('minecraft:{name.lower()}', {fd['nutrition']}, {sat!r}, {'true' if fd['always'] else 'false'}, {ticks}, {rem})")
print(",\n".join(rows) + ";")
