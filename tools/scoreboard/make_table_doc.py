#!/usr/bin/env python3
"""Write docs/SCOREBOARD-table.md (the full generated table) and keep the raw results next to it.
usage: make_table_doc.py   (run from anywhere; reads $SCORE_OUT/results.jsonl)"""
import os, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import common as C

docs = os.path.join(C.REPO, "docs")
tags = "core,storm,misc2,misc3,tail2,tail-unbounded"
table = subprocess.run([sys.executable, os.path.join(HERE, "aggregate.py"), "--tags", tags], capture_output=True, text=True).stdout
head = ("# Scoreboard: full generated table\n\n"
        "Generated by `tools/scoreboard/aggregate.py` from the raw results (`docs/scoreboard-results.jsonl.txt`, timing data only; regenerate with\n"
        "`tools/scoreboard/matrix.py` and `rerun.sh`/`rerun2.sh`).  Median over the repetitions with [min-max]; ratio = dbcraft / vanilla; lower is better except\n"
        "edits per second.  See docs/SCOREBOARD.md for how to read it and what is NOT comparable.\n\n")
open(os.path.join(docs, "SCOREBOARD-table.md"), "w").write(head + table)
shutil.copy(os.path.join(C.OUT, "results.jsonl"), os.path.join(docs, "scoreboard-results.jsonl.txt"))
print("wrote docs/SCOREBOARD-table.md (%d lines) and docs/scoreboard-results.jsonl.txt" % len(table.splitlines()))
