#!/usr/bin/env python3
"""Write docs/SCOREBOARD-table.md (every row of the final campaign, generated) and the raw results next to it.
usage: tools/scoreboard/cenv python3 tools/scoreboard/make_final_docs.py [MOBS_DIR=/dev/shm/sb/mobs]
Raw files: docs/scoreboard-results.jsonl.txt (every run of the campaign, including the diagnosis cells and the discarded first soak attempt), docs/scoreboard-results-mobs.jsonl.txt."""
import json, os, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import common as C

docs = os.path.join(C.REPO, "docs")
mobs = sys.argv[1] if len(sys.argv) > 1 else "/dev/shm/sb/mobs"
res = os.path.join(C.OUT, "results.jsonl")


def run(*a):
    return subprocess.run([sys.executable, *a], capture_output=True, text=True, check=True).stdout


table = run(os.path.join(HERE, "final_report.py"), res)
mobs_t = run(os.path.join(HERE, "mobs_report.py"), mobs)
diag_t = run(os.path.join(HERE, "diag_report.py"), res)
head = """# Scoreboard: the full generated table of the final campaign

Generated by `tools/scoreboard/final_report.py`, `mobs_report.py` and `diag_report.py` (written by `tools/scoreboard/make_final_docs.py`) from the raw results of ONE campaign on ONE tree
(`docs/scoreboard-results.jsonl.txt`, `docs/scoreboard-results-mobs.jsonl.txt`).  Median over the repetitions with [min-max]; ratio = dbcraft / vanilla; a difference is a TIE when the
two [min-max] ranges overlap, otherwise the winner is named with the factor between the medians.  The last column is the 1-minute load average when each cell started (the gate was 1.5).
How to read it, what each row measures, and what dbcraft does NOT do that vanilla does: [SCOREBOARD.md](SCOREBOARD.md).  The previous session's table is `SCOREBOARD-table-2026-11-02.md`.

## Everything except mobs

"""
with open(os.path.join(docs, "SCOREBOARD-table.md"), "w") as f:
    f.write(head + table + "\n\n## Mobs (tools/scoreboard/mobs.sh)\n\nvanilla: CPU of the Server thread per tick; dbcraft: on-CPU ms of the entity tick (inline mode).  " +
            "Simulation distance 10 on both sides.\n\n" + mobs_t + "\n\n## Diagnosis: dbcraft with `dbcraft.dynamics = off` (tools/scoreboard/diag.sh, not a supported configuration of the headline table)\n\n" + diag_t + "\n")
shutil.copy(res, os.path.join(docs, "scoreboard-results.jsonl.txt"))
with open(os.path.join(docs, "scoreboard-results-mobs.jsonl.txt"), "w") as f:
    for l in open(os.path.join(mobs, "vanilla.jsonl")):
        f.write(l)
    for l in open(os.path.join(mobs, "dbcraft.txt")):
        if l.startswith("rep "):
            f.write(json.dumps({"server": "dbcraft", "line": l.strip()}) + "\n")
    p = os.path.join(mobs, "diag_benchdb.txt")
    if os.path.exists(p):
        for l in open(p):
            f.write(json.dumps({"server": "dbcraft", "diag": "bench database, simulation distance 3", "line": l.strip()}) + "\n")
soak1 = os.path.join(C.OUT, "soak-attempt1-harness-bug.jsonl")
if os.path.exists(soak1):
    with open(os.path.join(docs, "scoreboard-results.jsonl.txt"), "a") as f:
        for l in open(soak1):
            r = json.loads(l)
            r["tag"] = "soak-attempt1-harness-bug"
            f.write(json.dumps(r) + "\n")
print("wrote docs/SCOREBOARD-table.md and the raw files")
